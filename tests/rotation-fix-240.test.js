test('render rotation 90 with a fade transition renders at the project size', async () => {
  const tl = timelineWithClip((t) => {
    const a = defaultClip('video', mediaVideo.id, 0, 2);
    const b = defaultClip('video', mediaVideo.id, 2, 2);
    b.rotation = 90;
    b.transition = { type: 'fade', duration: 0.5 };
    t.tracks[0].clips.push(a, b);
  });
  const { video, duration } = await renderTimeline(tl, 'rot90fade');
  assert.equal(video.width, 1280);
  assert.equal(video.height, 720);
  assert.ok(Math.abs(duration - 3.5) < 0.75, `duration ${duration}, expected 3.5 (4s minus 0.5s fade)`);
});

