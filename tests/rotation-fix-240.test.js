'use strict';
// Rotation-fix regression tests (v2.4.0) — the complete CapCut analysis
// (§3.2) found that rotation 90°/270° broke every render: alone the output
// came out transposed (720×1280) and the validator failed it; with a fade
// transition xfade failed (FFmpeg exit 234) because the rotated segment did
// not match the other input's size. 180° worked. The fix scales+pads the
// rotated frame back to the project size right after the transpose, in both
// the plain and the keyframed chains (and on the overlay track). The same
// analysis found POST /api/video/validate silently accepted keyframes
// carrying rotation/volume — properties the renderer never honours — so
// validation now rejects unknown keyframe properties with a clear error.
// Spawns the real server on a scratch port (4849) with a temp DB/uploads/
// renders/models dir. Run with: npm test
const { test, before, after } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawn, execFile, execFileSync } = require('child_process');

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'cs-pro-rotation240-test-'));
const dbPath = path.join(tmp, 'test.db');
const uploadsDir = path.join(tmp, 'uploads');
const rendersDir = path.join(tmp, 'renders');
const modelsDir = path.join(tmp, 'models');
process.env.DB_PATH = dbPath;
process.env.UPLOADS_DIR = uploadsDir;
process.env.RENDERS_DIR = rendersDir;
process.env.MODELS_DIR = modelsDir;
// Keyframed renders are slow (~0.06x realtime on this box); a 2s keyframed
// clip can take ~35s, so the watchdog override is 120s, not 30s.
process.env.RENDER_WATCHDOG_MS = '120000';
const PORT = 4849;
const BASE = `http://127.0.0.1:${PORT}`;

const { blankTimeline, defaultClip } = require('../src/video-model');

let server;
let ownerCookie = '';
let mediaVideo;
let mediaPng;

function req(p, { method = 'GET', body, cookie, form } = {}) {
  const headers = { connection: 'close' };
  if (cookie) headers.cookie = cookie;
  let payload;
  if (body !== undefined) { headers['Content-Type'] = 'application/json'; payload = JSON.stringify(body); }
  if (form) payload = form;
  return fetch(BASE + p, { method, headers, body: payload, redirect: 'manual' })
    .then(async (r) => {
      const text = await r.text();
      let json = null;
      try { json = JSON.parse(text); } catch { /* not JSON */ }
      return { status: r.status, json, text, setCookie: r.headers.get('set-cookie') || '' };
    });
}

function ffprobe(file) {
  return new Promise((resolve, reject) => {
    execFile('ffprobe', ['-v', 'error', '-show_entries', 'stream=codec_type,codec_name,width,height,avg_frame_rate', '-show_entries', 'format=duration', '-of', 'json', file],
      (err, stdout) => (err ? reject(err) : resolve(JSON.parse(stdout))));
  });
}

function makeTestVideo(file, seconds, tone) {
  execFileSync('ffmpeg', ['-y', '-v', 'error',
    '-f', 'lavfi', '-i', `testsrc=duration=${seconds}:size=320x180:rate=30`,
    '-f', 'lavfi', '-i', `sine=frequency=${tone}:duration=${seconds}`,
    '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-shortest', file],
    { timeout: 60000 });
}

// A valid PNG, generated by FFmpeg — never a hand-embedded base64 blob.
function makePng(outPath) {
  execFileSync('ffmpeg', ['-y', '-f', 'lavfi', '-i', 'color=c=0x2e7d32:s=64x64:d=1:r=1', '-frames:v', '1', outPath], { stdio: 'pipe' });
}

async function uploadFile(name, buf, mime) {
  const fd = new FormData();
  fd.append('file', new Blob([buf], { type: mime }), name);
  const r = await req('/api/media/upload', { method: 'POST', cookie: ownerCookie, form: fd });
  assert.equal(r.status, 201, `upload ${name} should be accepted: ${r.text}`);
  return r.json.media;
}

async function renderTimeline(tl, label) {
  const job = await req('/api/video/jobs', { method: 'POST', cookie: ownerCookie, body: { timeline: tl, settings: { resolution: '720p', fps: 30 } } });
  assert.equal(job.status, 201, `render ${label}: job should be created: ${JSON.stringify(job.json)}`);
  const id = job.json.job.id;
  const deadline = Date.now() + 120000;
  let last = null;
  for (;;) {
    const r = await req(`/api/video/jobs/${id}`, { cookie: ownerCookie });
    assert.equal(r.status, 200, `job ${id} should be readable: ${r.text}`);
    last = r.json.job;
    if (['done', 'failed', 'cancelled'].includes(last.status)) break;
    assert.ok(Date.now() < deadline, `render ${label} did not finish within 120s (last: ${JSON.stringify(last)})`);
    await new Promise((x) => setTimeout(x, 1000));
  }
  assert.equal(last.status, 'done', `render ${label} failed: ${last.error || 'unknown'}`);
  const outFile = path.join(tmp, `${label}.mp4`);
  const buf = Buffer.from(await fetch(BASE + `/api/video/jobs/${id}/download`, { headers: { cookie: ownerCookie } }).then((r) => r.arrayBuffer()));
  fs.writeFileSync(outFile, buf);
  const probe = await ffprobe(outFile);
  const video = probe.streams.find((s) => s.codec_type === 'video');
  assert.ok(video, `render ${label}: output has a video stream`);
  return { job: last, probe, video, duration: parseFloat(probe.format.duration) };
}

function timelineWithClip(setup) {
  const tl = blankTimeline('16:9', 30);
  setup(tl);
  return tl;
}

before(async () => {
  const vidPath = path.join(tmp, 'clip.mp4');
  makeTestVideo(vidPath, 4, 440);
  const pngPath = path.join(tmp, 'sticker.png');
  makePng(pngPath);
  const env = {
    ...process.env,
    DB_PATH: dbPath, UPLOADS_DIR: uploadsDir, RENDERS_DIR: rendersDir, MODELS_DIR: modelsDir,
    PORT: String(PORT), HOST: '127.0.0.1', RENDER_WATCHDOG_MS: '120000',
  };
  server = spawn(process.execPath, ['server.js'], { cwd: path.resolve(__dirname, '..'), env, stdio: ['ignore', 'pipe', 'pipe'] });
  let out = '';
  server.stdout.on('data', (d) => { out += d; });
  server.stderr.on('data', (d) => { out += d; });
  const deadline = Date.now() + 20000;
  for (;;) {
    try {
      const r = await fetch(`${BASE}/api/health`);
      if (r.ok) break;
    } catch { /* not up yet */ }
    if (Date.now() > deadline) throw new Error(`server did not start: ${out}`);
    await new Promise((x) => setTimeout(x, 200));
  }
  const s = await req('/api/auth/signup', { method: 'POST', body: { name: 'Rotation Tester', email: 'rotation@test.local', password: 'password123' } });
  assert.equal(s.status, 201, JSON.stringify(s.json));
  ownerCookie = s.setCookie.split(';')[0];
  mediaVideo = await uploadFile('clip.mp4', fs.readFileSync(vidPath), 'video/mp4');
  mediaPng = await uploadFile('sticker.png', fs.readFileSync(pngPath), 'image/png');
});

after(async () => {
  if (server) server.kill('SIGKILL');
});

test('validate accepts a keyframe carrying rotation (v2.5.0 #5)', async () => {
  const tl = timelineWithClip((t) => {
    const c = defaultClip('video', mediaVideo.id, 0, 2);
    c.keyframes = [{ t: 0, x: 50, y: 50, scale: 1, opacity: 1, rotation: 90 }];
    t.tracks[0].clips.push(c);
  });
  const r = await req('/api/video/validate', { method: 'POST', cookie: ownerCookie, body: { timeline: tl } });
  assert.equal(r.status, 200);
  assert.equal(r.json.valid, true, `a rotation keyframe must validate in v2.5.0: ${JSON.stringify(r.json.errors)}`);
  // Out-of-range rotation is still rejected (0–360).
  const tl2 = timelineWithClip((t) => {
    const c = defaultClip('video', mediaVideo.id, 0, 2);
    c.keyframes = [{ t: 0, x: 50, y: 50, scale: 1, opacity: 1, rotation: 400 }];
    t.tracks[0].clips.push(c);
  });
  const r2 = await req('/api/video/validate', { method: 'POST', cookie: ownerCookie, body: { timeline: tl2 } });
  assert.equal(r2.json.valid, false, 'rotation above 360 must not validate');
});

