test('gap: corrupt image render fails honestly (watchdog) and the queue recovers', async () => {
  // A valid PNG truncated to 40 bytes: uploads as image media (kind comes
  // from the mimetype), but FFmpeg can never decode it — with -loop 1 it
  // used to retry forever and brick the single-slot render queue, so every
  // later render stayed queued. The watchdog must kill it and fail the job.
  const goodPath = path.join(tmp, 'watchdog-good.png');
  makePng(goodPath);
  const corruptPath = path.join(tmp, 'watchdog-bad.png');
  fs.writeFileSync(corruptPath, fs.readFileSync(goodPath).subarray(0, 40));
  const bad = await uploadFile('watchdog-bad.png', fs.readFileSync(corruptPath), 'image/png');
  assert.equal(bad.kind, 'image', 'truncated PNG still uploads as image media');
  const tl = blankTimeline('16:9', 30);
  tl.tracks.find((t) => t.kind === 'video').clips.push(defaultClip('video', bad.id, 0, 3));
  const p = await createProject('Gap Watchdog Project', 'video', { timeline: tl });
  const r = await req('/api/video/jobs', { method: 'POST', cookie: ownerCookie, body: { projectId: p.id, settings: { resolution: '720p', fps: 30 } } });
  assert.equal(r.status, 201, JSON.stringify(r.json));
  const failed = await pollJobUntil(r.json.job.id, ['failed'], 90000);
  assert.equal(failed.status, 'failed', 'corrupt render fails instead of hanging forever');
  assert.ok(/timed out|FFmpeg/i.test(failed.error || ''), `failure names the cause honestly (got: ${failed.error || ''})`);
  // The queue must recover: a good render straight after must complete.
  const mp4Path = path.join(tmp, 'watchdog-clip.mp4');
  makeClipMp4(mp4Path);
  const media = await uploadFile('watchdog-clip.mp4', fs.readFileSync(mp4Path), 'video/mp4');
  const tl2 = blankTimeline('16:9', 30);
  tl2.tracks.find((t) => t.kind === 'video').clips.push(defaultClip('video', media.id, 0, 2));
  const p2 = await createProject('Gap Watchdog Recovery', 'video', { timeline: tl2 });
  const r2 = await req('/api/video/jobs', { method: 'POST', cookie: ownerCookie, body: { projectId: p2.id, settings: { resolution: '720p', fps: 30 } } });
  assert.equal(r2.status, 201, JSON.stringify(r2.json));
  const done = await pollJob(r2.json.job.id);
  assert.equal(done.status, 'done', 'a good render completes right after the failed one');
});

