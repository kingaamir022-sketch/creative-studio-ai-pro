function req(p, { method = 'GET', body, cookie, form, raw } = {}) {
  const headers = { connection: 'close' };
  if (cookie) headers.cookie = cookie;
  let payload;
  if (body !== undefined) { headers['Content-Type'] = 'application/json'; payload = JSON.stringify(body); }
  if (form) payload = form; // FormData sets its own content-type
  if (raw !== undefined) payload = raw;
  return fetch(BASE + p, { method, headers, body: payload, redirect: 'manual' })
    .then(async (r) => {
      const text = await r.text();
      let json = null;
      try { json = JSON.parse(text); } catch { /* not JSON */ }
      return { status: r.status, json, text, headers: r.headers, setCookie: r.headers.get('set-cookie') || '' };
    });
}

async function reqBuffer(p, { cookie } = {}) {
  const headers = { connection: 'close' };
  if (cookie) headers.cookie = cookie;
  const r = await fetch(BASE + p, { headers, redirect: 'manual' });
  const buf = Buffer.from(await r.arrayBuffer());
  return { status: r.status, buf, headers: r.headers };
}

async function uploadFile(name, buf, mime) {
  const fd = new FormData();
  fd.append('file', new Blob([buf], { type: mime }), name);
  const r = await req('/api/media/upload', { method: 'POST', cookie: ownerCookie, form: fd });
  assert.equal(r.status, 201, `upload ${name} should be accepted: ${r.text}`);
  return r.json.media;
}

function makeClipMp4(outPath) {
  execFileSync('ffmpeg', ['-y', '-f', 'lavfi', '-i', 'color=c=0x1e2a4a:s=640x360:d=2:r=30',
    '-f', 'lavfi', '-i', 'anullsrc=r=44100:cl=stereo', '-t', '2', '-shortest',
    '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', outPath], { stdio: 'pipe' });
}

// A valid PNG, generated by FFmpeg — never a hand-embedded base64 blob:
// a truncated/corrupt 1x1 PNG once made this suite's sticker render loop
// forever (ffmpeg -loop 1 retries a broken image indefinitely).
function makePng(outPath) {
  execFileSync('ffmpeg', ['-y', '-f', 'lavfi', '-i', 'color=c=0x2e7d32:s=64x64:d=1:r=1', '-frames:v', '1', outPath], { stdio: 'pipe' });
}

async function pollJob(id, timeoutMs = 120000) {
  const deadline = Date.now() + timeoutMs;
  for (;;) {
    const r = await req(`/api/video/jobs/${id}`, { cookie: ownerCookie });
    assert.equal(r.status, 200, `job ${id} should be readable: ${r.text}`);
    if (r.json.job.status === 'done') return r.json.job;
    if (r.json.job.status === 'failed') assert.fail(`job ${id} failed: ${r.json.job.error || 'unknown'}`);
    assert.ok(Date.now() < deadline, `job ${id} did not finish within ${timeoutMs}ms`);
    await new Promise((res) => setTimeout(res, 2000));
  }
}

// Poll until the job reaches one of the wanted terminal states (used for
// jobs that are EXPECTED to fail — pollJob above treats 'failed' as fatal).
async function pollJobUntil(id, wanted, timeoutMs = 90000) {
  const deadline = Date.now() + timeoutMs;
  for (;;) {
    const r = await req(`/api/video/jobs/${id}`, { cookie: ownerCookie });
    assert.equal(r.status, 200, `job ${id} should be readable: ${r.text}`);
    if (wanted.includes(r.json.job.status)) return r.json.job;
    assert.ok(Date.now() < deadline, `job ${id} did not reach ${wanted.join('/')} within ${timeoutMs}ms (last: ${r.json.job.status})`);
    await new Promise((res) => setTimeout(res, 2000));
  }
}

